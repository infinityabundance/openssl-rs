/*
 * The twelve SLH-DSA keygen vectors shared by `rt_keymgmt_probe.c` and `rt_signature_probe.c`.
 *
 * Every byte below is read back from the authority's own `test/slh_dsa.inc` -- the ACVP
 * `SLH-DSA-sigGen-FIPS205` `internalProjection` set the authority's `slh_dsa_test.c` reads --
 * specifically each `<set>_0_keygen_priv` array, which is the full 4n private key
 * `SK_SEED || SK_PRF || PK_SEED || PK_ROOT`. Two things are driven from it on both sides:
 *
 *   * the first 3n bytes are the `seed` generation parameter (`SLH_DSA_KEYGEN_TEST_ITEM`'s
 *     `name##_keygen_priv` at `sizeof / 4 * 3`, which is what `slh_dsa_keygen_test` and this
 *     header's two arms pass), so `EVP_PKEY_generate` reproduces the vector's keypair;
 *   * the last 2n bytes are the expected `PK_SEED || PK_ROOT`, so the generated public key can
 *     be compared against the vector's own rather than against a second transcription.
 *
 * Nothing is typed: a wrong constant here would be agreed on by both sides and invisible to a
 * differential court, which is why the values come from the authority's data file (D392).
 */
