    def test_the_real_leaves_are_the_frozen_a9_statement_bytes(self) -> None:
        real = [leaf for leaf in self.fixture["leaves"] if leaf["kind"] == "real-statement"]
        self.assertEqual(len(real), 4)
        for leaf in real:
            raw = (REPO_ROOT / leaf["path"]).read_bytes()
            self.assertEqual(hashlib.sha256(raw).hexdigest(), leaf["sha256"])
            self.assertEqual(tlog.leaf_hash(raw).hex(), leaf["leafHash"])

    def test_the_synthetic_leaves_are_labelled_and_seeded(self) -> None:
        synthetic = [
            leaf for leaf in self.fixture["leaves"] if leaf["kind"] == "synthetic-test-only"
        ]
        self.assertEqual(len(synthetic), 2)
        for leaf in synthetic:
            self.assertIsNone(leaf["path"])
            expected = self.builder._synthetic_entry(leaf["index"])
            self.assertEqual(hashlib.sha256(expected).hexdigest(), leaf["sha256"])

    def test_the_tiles_reproduce_the_recorded_root(self) -> None:
        store = tlog.TileStore.from_directory(FIXTURE_DIR)
        root = store.root(TREE_SIZE)
        self.assertEqual(root.hex(), self.fixture["rootHash"])
        self.assertEqual(root.hex(), self.publication["rootHash"])
        store.verify_tiles(TREE_SIZE, root)

    def test_the_published_statement_is_included_and_bound(self) -> None:
        statement = PUBLISHED.read_bytes()
        store = tlog.TileStore.from_directory(FIXTURE_DIR)
        root = bytes.fromhex(self.publication["rootHash"])
        log = tlog.TiledLog(store, TREE_SIZE, root)
        proof = [bytes.fromhex(value) for value in self.publication["inclusionProof"]]
        log.verify_statement_inclusion(statement, PUBLISHED_INDEX, proof)
        self.assertEqual(
            hashlib.sha256(statement).hexdigest(),
            self.publication["statement"]["sha256"],
        )
        self.assertEqual(
            tlog.leaf_hash(statement).hex(), self.publication["leaf"]["leafHash"]
        )
        self.assertEqual(
            self.publication["binding"]["subjectDigest"],
            self.publication["statement"]["subjects"][0]["sha256"],
        )

    def test_the_checkpoints_verify_as_a_chain(self) -> None:
        store = tlog.TileStore.from_directory(FIXTURE_DIR)
        previous = None
        for path in ("checkpoint-2.note", "checkpoint-5.note", "checkpoint-6.note"):
            proof = None
            raw = (FIXTURE_DIR / path).read_bytes()
            size = tlog.parse_signed_checkpoint(raw)[0].size
            if previous is not None:
                proof = []
                if previous.size < size:
                    proof = tlog.TiledLog(
                        store, size, store.root(size)
                    ).consistency_proof(previous.size)
            head = tlog.verify_checkpoint(
                raw,
                key_name=SIGNER,
                key=KEY,
                expected_origin=ORIGIN,
                previous=previous,
                consistency_proof=proof,
                recomputed_root=store.root(size),
            )
            self.assertEqual(head.size, size)
            previous = head

