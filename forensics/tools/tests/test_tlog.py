#!/usr/bin/env python3
"""Controls for ``forensics/tools/tlog.py`` and the B1b fixture.

The verifier is checked in both directions: proofs generated by the RFC 6962
recursion are verified, proofs reconstructed from the C2SP tile layout are
verified, and a proof mutated in each field is refused.  The hashing vectors below
are **hand-computed** with ``hashlib`` alone, not with the module under test.

RFC 6962 supplies the construction but no official hash test vectors; the C2SP
``tlog-tiles`` / ``tlog-checkpoint`` vector files were not available in this
venue (no network).  The tests therefore use the RFC's own equations with
independently computed values, plus generated cases at tile boundaries.  None of
these is a conformance vector and this file does not claim they are.

The §B.24 controls are re-run from the producer and every refusal code has one
triggering case.  A control that fires proves the verifier refuses a corrupted
input; it does not prove a live Rekor service behaves as the fixture does.

SPDX-License-Identifier: Apache-2.0
"""

