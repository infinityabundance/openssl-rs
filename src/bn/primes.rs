/// The two exits of `ossl_bn_miller_rabin_is_prime`'s inner loop, which the authority
/// spells `goto outer_loop` and `goto composite`.
enum Outcome {
    /// `outer_loop:` — the round found `z == 1` or `z == w-1`, so `w` survives it.
    OuterLoop,
    /// `composite:` — the round found a witness, so `w` is composite.
    Composite,
}

/// `static int calc_trial_divisions(int bits)` — `crypto/bn/bn_prime.c:74-85`.
///
/// The thresholds are the authority's, and they are what makes the *number* of trial
/// divisions a function of the requested width rather than of the value.
fn calc_trial_divisions(bits: c_int) -> c_int {
    if bits <= 512 {
        64
    } else if bits <= 1024 {
        128
    } else if bits <= 2048 {
        384
    } else if bits <= 4096 {
        1024
    } else {
        NUMPRIMES as c_int
    }
}

/// `static int bn_mr_min_checks(int bits)` — `crypto/bn/bn_prime.c:94-99`.
///
/// Returns the number of Miller-Rabin rounds: 64 for a width up to 2048 bits and 128
/// above it. This is the clamp `ossl_bn_check_prime` applies to a caller's `checks`,
/// and a callback that counts rounds observes it.
fn bn_mr_min_checks(bits: c_int) -> c_int {
    if bits > 2048 {
        128
    } else {
        64
    }
}

/// `int ossl_bn_miller_rabin_is_prime(const BIGNUM *w, int iterations,`
/// `BN_CTX *ctx, BN_GENCB *cb, int enhanced, int *status)` —
/// `crypto/bn/bn_prime.c:347-476`, declared in `include/crypto/bn.h:106`.
///
/// FIPS 186-4 C.3.1 (probabilistic) or C.3.2 (enhanced) Miller-Rabin. The step
/// numbers in the authority's comments refer to the enhanced case and are
/// reproduced here.
///
/// This crate's only caller is [`bn_is_prime_int`], which passes `enhanced = 0`; the
/// `enhanced` arms are transcribed rather than omitted because they are the *same
/// function* in the authority, and the reader of `include/crypto/bn.h`'s declaration
/// reaches them through `ossl_bn_rsa_fips186_4_derive_prime`
/// (`crypto/bn/bn_rsa_fips186_4.c:391`), which is Phase 8's RSA key generation.
///
/// Answers `0` only for the errors — a non-odd `w`, `w <= 3`, a failed allocation or
/// a callback that stopped the loop — and `1` otherwise, with the verdict in
/// `*status`.
///
/// # Safety
///
/// `w` must be null or live; `ctx` must be null or a live `BN_CTX`; `cb` must be null
/// or a live `BN_GENCB` whose callback is safe to call; `status` must point to a
/// writable `int`.
pub(crate) unsafe fn ossl_bn_miller_rabin_is_prime(
    w: *const BigNum,
    iterations: c_int,
    ctx: *mut BnCtx,
    cb: *mut BnGencb,
    enhanced: c_int,
    status: *mut c_int,
) -> c_int {
    /* w must be odd */
    // SAFETY: `w` is null-or-live per this function's `# Safety` section, which
    // `BN_is_odd` also accepts.
    if unsafe { BN_is_odd(w) } == 0 {
        return 0;
    }

    // SAFETY: `ctx` is null or live per this function's `# Safety` section.
    unsafe { BN_CTX_start(ctx) };
    // SAFETY: as above; each call allocates or reuses a cleared pool slot.
    let (g, w1, w3, x, m, z, b) = unsafe {
        (
            BN_CTX_get(ctx),
            BN_CTX_get(ctx),
            BN_CTX_get(ctx),
            BN_CTX_get(ctx),
            BN_CTX_get(ctx),
            BN_CTX_get(ctx),
            BN_CTX_get(ctx),
        )
    };
    // SAFETY: `BN_MONT_CTX_new` takes no pointers.
    let mont = unsafe { BN_MONT_CTX_new() };

    let mut ret: c_int = 0;
    (|| {
        // SAFETY: every pointer below is either an object this call has just made (or
        // a null it must check), or the caller's under this function's contract.
        unsafe {
            if b.is_null() {
                return;
            }
            /* w1 := w - 1 */
            if BN_copy(w1, w).is_null() || BN_sub_word(w1, 1) == 0 {
                return;
            }
            /* w3 := w - 3 */
            if BN_copy(w3, w).is_null() || BN_sub_word(w3, 3) == 0 {
                return;
            }
            // `w` must be larger than 3, otherwise the random `b` is too small.
            if BN_is_zero(w3) != 0 || BN_is_negative(w3) != 0 {
                return;
            }

            /* (Step 1) Calculate largest integer 'a' such that 2^a divides w-1 */
            let mut a: c_int = 1;
            while BN_is_bit_set(w1, a) == 0 {
                a += 1;
            }
            /* (Step 2) m = (w-1) / 2^a */
            if BN_rshift(m, w1, a) == 0 {
                return;
            }

            /* Montgomery setup for computations mod w */
            if mont.is_null() || BN_MONT_CTX_set(mont, w, ctx) == 0 {
                return;
            }

            let iterations = if iterations == 0 {
                bn_mr_min_checks(BN_num_bits(w))
            } else {
                iterations
            };

            /* (Step 4) */
            let mut i: c_int = 0;
            while i < iterations {
                /* (Step 4.1) obtain a Random string of bits b where 1 < b < w-1 */
                if BN_priv_rand_range_ex(b, w3, 0, ctx) == 0 || BN_add_word(b, 2) == 0 {
                    return;
                }

                if enhanced != 0 {
                    /* (Step 4.3) */
                    if BN_gcd(g, b, w, ctx) == 0 {
                        return;
                    }
                    /* (Step 4.4) */
                    if BN_is_one(g) == 0 {
                        *status = BN_PRIMETEST_COMPOSITE_WITH_FACTOR;
                        ret = 1;
                        return;
                    }
                }
                /* (Step 4.5) z = b^m mod w */
                if BN_mod_exp_mont(z, b, m, w, ctx, mont) == 0 {
                    return;
                }

                let outcome = if BN_is_one(z) != 0 || BN_cmp(z, w1) == 0 {
                    /* (Step 4.6) if (z = 1 or z = w-1) */
                    Outcome::OuterLoop
                } else {
                    /* (Step 4.7) for j = 1 to a-1 */
                    let mut found: Option<Outcome> = None;
                    let mut j: c_int = 1;
                    while j < a {
                        /* (Step 4.7.1 - 4.7.2) x = z. z = x^2 mod w */
                        if BN_copy(x, z).is_null() || BN_mod_mul(z, x, x, w, ctx) == 0 {
                            return;
                        }
                        /* (Step 4.7.3) */
                        if BN_cmp(z, w1) == 0 {
                            found = Some(Outcome::OuterLoop);
                            break;
                        }
                        /* (Step 4.7.4) */
                        if BN_is_one(z) != 0 {
                            found = Some(Outcome::Composite);
                            break;
                        }
                        j += 1;
                    }
                    match found {
                        Some(o) => o,
                        None => {
                            // At this point z = b^((w-1)/2) mod w.
                            /* (Steps 4.8 - 4.9) x = z, z = x^2 mod w */
                            if BN_copy(x, z).is_null() || BN_mod_mul(z, x, x, w, ctx) == 0 {
                                return;
                            }
                            /* (Step 4.10) */
                            if BN_is_one(z) != 0 {
                                Outcome::Composite
                            } else {
                                /* (Step 4.11) x = b^(w-1) mod w */
                                if BN_copy(x, z).is_null() {
                                    return;
                                }
                                // The authority's body then runs on into its
                                // `composite:` label: past step 4.11 the candidate has
                                // failed a round.
                                Outcome::Composite
                            }
                        }
                    }
                };

                match outcome {
                    Outcome::OuterLoop => {
                        /* (Step 4.1.5) */
                        if BN_GENCB_call(cb, 1, i) == 0 {
                            return;
                        }
                    }
                    Outcome::Composite => {
                        if enhanced != 0 {
                            /* (Step 4.1.2) g = GCD(x-1, w) */
                            if BN_sub_word(x, 1) == 0 || BN_gcd(g, x, w, ctx) == 0 {
                                return;
                            }
                            /* (Steps 4.1.3 - 4.1.4) */
                            *status = if BN_is_one(g) != 0 {
                                BN_PRIMETEST_COMPOSITE_NOT_POWER_OF_PRIME
                            } else {
                                BN_PRIMETEST_COMPOSITE_WITH_FACTOR
                            };
                        } else {
                            *status = BN_PRIMETEST_COMPOSITE;
                        }
                        ret = 1;
                        return;
                    }
                }
                i += 1;
            }
            /* (Step 5) */
            *status = BN_PRIMETEST_PROBABLY_PRIME;
            ret = 1;
        }
    })();

    // Each of the seven is null or a pool object, and `BN_clear` accepts null — which
    // is the authority's own `BN_clear` contract too.
    // SAFETY: as above, and `ctx`/`mont` are unmodified.
    unsafe {
        BN_clear(g);
        BN_clear(w1);
        BN_clear(w3);
        BN_clear(x);
        BN_clear(m);
        BN_clear(z);
        BN_clear(b);
        BN_CTX_end(ctx);
        BN_MONT_CTX_free(mont);
    }
    ret
}

/// `static int bn_is_prime_int(const BIGNUM *w, int checks, BN_CTX *ctx,`
/// `int do_trial_division, BN_GENCB *cb)` — `crypto/bn/bn_prime.c:275-330`.
///
/// `0` for composite, `1` for probable prime, `-1` for an error. The three
/// deterministic exits come first and are the ones that make this function testable
/// without a RNG: `w <= 1`, an even `w` (only `2` is prime), and a `w` divisible by
/// one of the trial primes (only itself is prime).
///
/// The `FIPS_MODULE` arm — `if (ctx == NULL) return -1;` — is not this profile's: no
/// FIPS module is built (`docs/PHASE-9-SUBPHASES.md` §1), so the temporary-context
/// branch is what the authority's shipped build runs.
///
/// # Safety
///
/// `w` must be null or live; `ctx` must be null or a live `BN_CTX`; `cb` must be null
/// or a live `BN_GENCB` whose callback is safe to call.
pub(crate) unsafe fn bn_is_prime_int(
    w: *const BigNum,
    checks: c_int,
    ctx: *mut BnCtx,
    do_trial_division: c_int,
    cb: *mut BnGencb,
) -> c_int {
    /* w must be bigger than 1 */
    // SAFETY: `w` is null-or-live and `BN_value_one` takes no caller pointer.
    if unsafe { BN_cmp(w, BN_value_one()) } <= 0 {
        return 0;
    }

    /* w must be odd */
    // SAFETY: `w` is null or live per this function's `# Safety` section.
    if unsafe { BN_is_odd(w) } != 0 {
        /* Take care of the really small prime 3 */
        // SAFETY: as above.
        if unsafe { BN_is_word(w, 3) } != 0 {
            return 1;
        }
    } else {
        /* 2 is the only even prime */
        // SAFETY: as above.
        return unsafe { BN_is_word(w, 2) };
    }

    /* first look for small factors */
    if do_trial_division != 0 {
        // SAFETY: `w` is null or live.
        let trial_divisions = calc_trial_divisions(unsafe { BN_num_bits(w) });
        let mut i: c_int = 1;
        while i < trial_divisions {
            let p = PRIMES[i as usize];
            // SAFETY: `w` is null or live.
            let m = unsafe { BN_mod_word(w, p as c_ulong) };
            if m == c_ulong::MAX {
                return -1;
            }
            if m == 0 {
                // SAFETY: as above.
                return unsafe { BN_is_word(w, p as c_ulong) };
            }
            i += 1;
        }
        // SAFETY: `cb` is null or live.
        if unsafe { BN_GENCB_call(cb, 1, -1) } == 0 {
            return -1;
        }
    }

    let mut ctxlocal: *mut BnCtx = core::ptr::null_mut();
    if ctx.is_null() {
        // SAFETY: `BN_CTX_new` takes no pointers.
        let fresh = unsafe { BN_CTX_new() };
        if fresh.is_null() {
            // The authority's `goto err` with `ret == -1`; `ctxlocal` is still null,
            // so the clearing free has nothing to release.
            return -1;
        }
        ctxlocal = fresh;
    }
    let ctx = if ctx.is_null() { ctxlocal } else { ctx };

    let mut status: c_int = 0;
    // SAFETY: `w` is null or live, `ctx` is live, `cb` is null or live, and `status`
    // is this frame's slot.
    let ok = unsafe { ossl_bn_miller_rabin_is_prime(w, checks, ctx, cb, 0, &mut status) };
    let ret = if ok == 0 {
        -1
    } else {
        c_int::from(status == BN_PRIMETEST_PROBABLY_PRIME)
    };
    // SAFETY: `ctxlocal` is null or the object `BN_CTX_new` returned here, and
    // `BN_CTX_free` accepts null.
    unsafe { BN_CTX_free(ctxlocal) };
    ret
}

