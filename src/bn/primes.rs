        ///
        /// As `call_check_prime`.
        unsafe fn call_fasttest_ex(w: *const BigNum, ctx: *mut BnCtx, cb: *mut BnGencb) -> c_int {
            // SAFETY: the caller's contract is this function's.
            unsafe { BN_is_prime_fasttest_ex(w, 5, ctx, 1, cb) }
        }

