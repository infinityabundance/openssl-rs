//! Phase 5 — the primality tests and prime generators, and the authority's named
//! primes.
//!
//! Two unrelated things share this module because the ledger assigns both here, and
//! they are kept apart below by a banner comment: the `BN_get0_nist_prime_*` and
//! `BN_get_rfc*_prime_*` families whose data lives in `crate::bn::prime_data`, and
//! the prime *behaviour* of `crypto/bn/bn_prime.c`, `crypto/bn/bn_x931p.c` and
//! `crypto/bn/bn_depr.c`.
//!
//! ## The named primes
//!
//! The values live in `crate::bn::prime_data`, which is generated from the admitted
//! authority rather than transcribed (see `forensics/tools/gen_bn_primes.py` for why).
//! This module is the API over them, and it has two ownership shapes that are easy to
//! conflate:
//!
//! * `BN_get0_nist_prime_*` returns a pointer to **static storage**. The caller must
//!   not modify or free it, and two calls return the same pointer — which a caller can
//!   observe by comparison, so the object is built once and cached rather than built
//!   per call.
//! * `BN_get_rfc2409_prime_*`/`BN_get_rfc3526_prime_*` take a destination: a null one
//!   means "allocate and return", a non-null one means "write here and return it".
//!   That is the authority's `COPY_BN` macro, and it is the same asymmetry `BN_bin2bn`
//!   has.
//!
//! ## The prime behaviour
//!
//! `BN_generate_prime_ex2` and `BN_check_prime` are the two entry points every key
//! generator in this library reaches, and the twelve functions around them are their
//! surface: the sieve (`probable_prime`, `probable_prime_dh`), the Miller-Rabin test
//! (`ossl_bn_miller_rabin_is_prime`) and the trial division above it
//! (`bn_is_prime_int`), the X9.31 derivation (`bn_x931_derive_pi`,
//! `BN_X931_derive_prime_ex`, `BN_X931_generate_prime_ex`, `BN_X931_generate_Xpq`),
//! and the three deprecated spellings `bn_depr.c` forwards.
//!
//! **The first 2048 primes are data, and they are generated.** `crypto/bn/bn_prime.h`
//! is itself generated by `crypto/bn/bn_prime.pl`, and [`PRIMES`] is that header read
//! back rather than typed: 2048 five-digit literals are exactly the kind of thing a
//! human transcribes with one wrong digit, and a wrong entry changes which candidates
//! the sieve discards rather than failing. The module test
//! `the_small_primes_are_the_first_2048_primes` re-derives the sequence with a sieve
//! and compares, so the table is checked rather than trusted.
//!
//! ## Callees, and the two that are substitutions rather than transcriptions
//!
//! Everything the bodies below call is the authority's own name in this crate, with
//! two exceptions, both recorded at their call sites:
//!
//! * `bn_mul_mont_fixed_top` and `bn_to_mont_fixed_top` are `crypto/bn/bn_mont.c`
//!   internals this crate has no name for, and `src/bn/blinding.rs` reaches their
//!   arithmetic through this crate's `BN_mod_mul_montgomery`/`BN_to_montgomery`
//!   instead.
//! * `int_bn_mod_inverse` (`crypto/bn/bn_gcd.c:197`) is likewise absent by name; what
//!   `BN_BLINDING_create_param` needs of it — an inversion that raises nothing and
//!   reports "not coprime" separately — is written out there.

