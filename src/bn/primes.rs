    /// The internal `ossl_bn_miller_rabin_is_prime`, driven directly. Its error exits are
    /// `w` even and `w <= 3`, and with `enhanced = 0` — the only value this crate passes — a
    /// composite always lands on `BN_PRIMETEST_COMPOSITE`, which is what makes the status
    /// observable rather than the witness random.
    #[test]
    fn the_miller_rabin_internal_reports_through_its_status_pointer() {
        // SAFETY: `BN_CTX_new` takes no pointers.
        let ctx = unsafe { BN_CTX_new() };
        let mut status: c_int;

        // The error exits answer 0 and touch nothing.
        for value in [4u64, 3, 1] {
            let w = word(value);
            status = -1;
            // SAFETY: `w` and `ctx` are live, `cb` is null and `status` is this frame's.
            let got = unsafe {
                ossl_bn_miller_rabin_is_prime(w, 1, ctx, core::ptr::null_mut(), 0, &mut status)
            };
            assert_eq!(got, 0, "w={value}");
            assert_eq!(status, -1, "w={value}: no verdict is written");
            // SAFETY: `w` was allocated in this loop.
            unsafe { BN_free(w) };
        }

        // A prime survives every round; a composite never does, and with `enhanced = 0` the
        // verdict is always the same code.
        let prime = word(5);
        status = -1;
        // SAFETY: every pointer is live or null.
        let got = unsafe {
            ossl_bn_miller_rabin_is_prime(prime, 1, ctx, core::ptr::null_mut(), 0, &mut status)
        };
        assert_eq!(got, 1);
        assert_eq!(status, BN_PRIMETEST_PROBABLY_PRIME);

        for value in [9u64, 104_927] {
            let w = word(value);
            status = -1;
            // SAFETY: every pointer is live or null.
            let got = unsafe {
                ossl_bn_miller_rabin_is_prime(w, 4, ctx, core::ptr::null_mut(), 0, &mut status)
            };
            assert_eq!(got, 1, "w={value}");
            assert_eq!(status, BN_PRIMETEST_COMPOSITE, "w={value}");
            // SAFETY: `w` was allocated in this loop.
            unsafe { BN_free(w) };
        }

        // The enhanced arm is reachable only by the same function with `enhanced != 0`. Its
        // *code* is draw-dependent (`WITH_FACTOR` when the witness shares a factor, otherwise
        // one of the two not-power-of-prime branches), so only "not probably prime" is
        // asserted.
        let w = word(9);
        status = -1;
        // SAFETY: every pointer is live or null.
        let got = unsafe {
            ossl_bn_miller_rabin_is_prime(w, 4, ctx, core::ptr::null_mut(), 1, &mut status)
        };
        assert_eq!(got, 1);
        assert_ne!(status, BN_PRIMETEST_PROBABLY_PRIME);

        // SAFETY: every object was allocated in this test.
        unsafe {
            BN_free(w);
            BN_free(prime);
            BN_CTX_free(ctx);
        }
    }

    /// **The small-factors object is the product of the primes from 3 to 751.** The
    /// authority's seventeen limbs are transcribed with its own `BN_DEF(lo, hi)`
    /// grouping, and this test re-derives the value from the sieve table above rather
    /// than trusting the hexadecimal constants -- the same argument the sieve table's
    /// own test makes. It also pins the two things a caller of
    /// `ossl_bn_get0_small_factors` observes: the value is 1037 bits, and two calls
    /// answer one shared address (it is a `static const BIGNUM` in the authority).
    #[test]
    fn the_small_prime_factors_are_the_product_of_the_primes_to_751() {
        let mut acc = limbs::from_u64(1);
        for &p in PRIMES.iter() {
            if p > 751 {
                break;
            }
            if p == 2 {
                continue; /* the authority's table starts at 3 */
            }
            acc = limbs::mul(&acc, &limbs::from_u64(p as u64));
        }
        assert_eq!(acc, SMALL_PRIME_FACTORS);
        assert_eq!(limbs::bit_len(&acc), 1037);

        // SAFETY: the object is shared static storage; two reads are the same address.
        let a = unsafe { ossl_bn_get0_small_factors() };
        // SAFETY: as above.
        let b = unsafe { ossl_bn_get0_small_factors() };
        assert!(!a.is_null());
        assert_eq!(a, b);
        // SAFETY: `a` is live shared storage.
        assert_eq!(unsafe { BN_num_bits(a) }, 1037);
    }

    /// **`ossl_bn_check_generated_prime` is `bn_is_prime_int` with trial division on
    /// and no clamp.** The point of the separate name is the un-clamped round count, so
    /// a call with `checks = 0` must *not* become `bn_mr_min_checks`: it becomes
    /// `bn_is_prime_int`'s own `iterations = 0`, which `ossl_bn_miller_rabin_is_prime`
    /// resolves to the minimum. Both spellings agree on a prime and on a composite
    /// here, and the value is that the argument reaches the callee unchanged.
    #[test]
    fn the_generated_prime_test_is_the_unclamped_spelling() {
        // SAFETY: every pointer is a fresh object this test owns or null.
        unsafe {
            let ctx = BN_CTX_new();
            assert!(!ctx.is_null());
            for (value, want) in [(97u64, 1), (91, 0), (2, 1), (1, 0)] {
                let w = BN_new();
                assert!(!w.is_null());
                assert_eq!(crate::bn::bignum::BN_set_word(w, value), 1);
                assert_eq!(
                    ossl_bn_check_generated_prime(w, 0, ctx, core::ptr::null_mut()),
                    want,
                    "generated-prime test of {value}"
                );
                BN_free(w);
            }
            BN_CTX_free(ctx);
        }
    }
