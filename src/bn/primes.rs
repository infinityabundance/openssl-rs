/// `static int probable_prime(BIGNUM *rnd, int bits, int safe, prime_t *mods,`
/// `BN_CTX *ctx)` — `crypto/bn/bn_prime.c:487-535`.
///
/// Zimmermann's sieve, as the authority's own comment records. The candidate is drawn
/// with `BN_RAND_TOP_TWO`/`BN_RAND_BOTTOM_ODD`, its residues against the first
/// `trial_divisions` primes are computed once, and then `delta` steps by 2 (or 4 for a
/// safe prime, keeping the cofactor odd) until every residue is non-zero. The closing
/// `BN_num_bits(rnd) != bits` test is what makes the caller's width a guarantee rather
/// than a hope, and `maxdelta` is what bounds the search.
///
/// # Safety
///
/// `rnd` must be null or a live, uniquely-owned `BIGNUM`; `mods` must be writable for
/// `NUMPRIMES` entries; `ctx` must be null or a live `BN_CTX`.
unsafe fn probable_prime(
    rnd: *mut BigNum,
    bits: c_int,
    safe: c_int,
    mods: *mut PrimeT,
    ctx: *mut BnCtx,
) -> c_int {
    let trial_divisions = calc_trial_divisions(bits);
    let maxdelta: c_ulong = BN_MASK2 - PRIMES[trial_divisions as usize - 1] as c_ulong;

    'again: loop {
        // SAFETY: `rnd` and `ctx` are as this function's `# Safety` section says, and
        // `mods` is writable for `NUMPRIMES` entries.
        unsafe {
            /* make a random number and set the top and bottom bits */
            if BN_priv_rand_ex(rnd, bits, BN_RAND_TOP_TWO, BN_RAND_BOTTOM_ODD, 0, ctx) == 0 {
                return 0;
            }
            if safe != 0 && BN_set_bit(rnd, 1) == 0 {
                return 0;
            }
            /* we now have a random number 'rnd' to test. */
            let mut i: c_int = 1;
            while i < trial_divisions {
                let m = BN_mod_word(rnd, PRIMES[i as usize] as c_ulong);
                if m == c_ulong::MAX {
                    return 0;
                }
                *mods.add(i as usize) = m as PrimeT;
                i += 1;
            }
            let mut delta: c_ulong = 0;
            'resieve: loop {
                let mut i: c_int = 1;
                while i < trial_divisions {
                    let p = PRIMES[i as usize] as c_ulong;
                    /*
                     * check that rnd is a prime and also that
                     * gcd(rnd-1,primes) == 1 (except for 2)
                     * do the second check only if we are interested in safe primes
                     * in the case that the candidate prime is a single word then
                     * we check only the primes up to sqrt(rnd)
                     */
                    if bits <= 31
                        && delta <= 0x7fff_ffff
                        && p * p > BN_get_word(rnd).wrapping_add(delta)
                    {
                        break;
                    }
                    let residue = (*mods.add(i as usize) as c_ulong).wrapping_add(delta) % p;
                    let divides = if safe != 0 {
                        residue <= 1
                    } else {
                        residue == 0
                    };
                    if divides {
                        delta += if safe != 0 { 4 } else { 2 };
                        if delta > maxdelta {
                            continue 'again;
                        }
                        continue 'resieve;
                    }
                    i += 1;
                }
                break;
            }
            if BN_add_word(rnd, delta) == 0 {
                return 0;
            }
            if BN_num_bits(rnd) != bits {
                continue 'again;
            }
            return 1;
        }
    }
}

/// `static int probable_prime_dh(BIGNUM *rnd, int bits, int safe, prime_t *mods,`
/// `const BIGNUM *add, const BIGNUM *rem, BN_CTX *ctx)` —
/// `crypto/bn/bn_prime.c:545-617`.
///
/// The same sieve for the `add`/`rem` form: the candidate must satisfy
/// `rnd % add == rem`, so the draw is reduced, moved onto the right residue and then
/// stepped by `add` rather than by 2. The `BN_mod` the authority writes is the
/// `BN_div` macro, which is why the quotient slot here is null.
///
/// # Safety
///
/// `rnd` must be null or a live, uniquely-owned `BIGNUM`; `mods` must be writable for
/// `NUMPRIMES` entries; `add` and `rem` must each be null or live; `ctx` must be null
/// or a live `BN_CTX`.
unsafe fn probable_prime_dh(
    rnd: *mut BigNum,
    bits: c_int,
    safe: c_int,
    mods: *mut PrimeT,
    add: *const BigNum,
    rem: *const BigNum,
    ctx: *mut BnCtx,
) -> c_int {
    let trial_divisions = calc_trial_divisions(bits);
    let mut maxdelta: c_ulong = BN_MASK2 - PRIMES[trial_divisions as usize - 1] as c_ulong;

    // SAFETY: `ctx` is null or live per this function's `# Safety` section.
    unsafe { BN_CTX_start(ctx) };
    // SAFETY: as above.
    let t1 = unsafe { BN_CTX_get(ctx) };
    let mut ret: c_int = 0;

    'body: {
        // SAFETY: every pointer is as this function's `# Safety` section says.
        unsafe {
            if t1.is_null() {
                break 'body;
            }

            let add_word = BN_get_word(add);
            if maxdelta > BN_MASK2 - add_word {
                maxdelta = BN_MASK2 - add_word;
            }

            'again: loop {
                if BN_rand_ex(rnd, bits, BN_RAND_TOP_ONE, BN_RAND_BOTTOM_ODD, 0, ctx) == 0 {
                    break 'body;
                }

                /* we need ((rnd-rem) % add) == 0 */
                if BN_div(core::ptr::null_mut(), t1, rnd, add, ctx) == 0 {
                    break 'body;
                }
                if BN_sub(rnd, rnd, t1) == 0 {
                    break 'body;
                }
                if rem.is_null() {
                    if BN_add_word(rnd, if safe != 0 { 3 } else { 1 }) == 0 {
                        break 'body;
                    }
                } else if BN_add(rnd, rnd, rem) == 0 {
                    break 'body;
                }

                if (BN_num_bits(rnd) < bits || BN_get_word(rnd) < if safe != 0 { 5 } else { 3 })
                    && BN_add(rnd, rnd, add) == 0
                {
                    break 'body;
                }

                /* we now have a random number 'rnd' to test. */
                let mut i: c_int = 1;
                while i < trial_divisions {
                    let m = BN_mod_word(rnd, PRIMES[i as usize] as c_ulong);
                    if m == c_ulong::MAX {
                        break 'body;
                    }
                    *mods.add(i as usize) = m as PrimeT;
                    i += 1;
                }
                let mut delta: c_ulong = 0;
                'resieve: loop {
                    let mut i: c_int = 1;
                    while i < trial_divisions {
                        let p = PRIMES[i as usize] as c_ulong;
                        /* check that rnd is a prime */
                        if bits <= 31
                            && delta <= 0x7fff_ffff
                            && p * p > BN_get_word(rnd).wrapping_add(delta)
                        {
                            break;
                        }
                        /* rnd mod p == 1 implies q = (rnd-1)/2 is divisible by p */
                        let residue = (*mods.add(i as usize) as c_ulong).wrapping_add(delta) % p;
                        let divides = if safe != 0 {
                            residue <= 1
                        } else {
                            residue == 0
                        };
                        if divides {
                            delta += add_word;
                            if delta > maxdelta {
                                continue 'again;
                            }
                            continue 'resieve;
                        }
                        i += 1;
                    }
                    break;
                }
                if BN_add_word(rnd, delta) == 0 {
                    break 'body;
                }
                ret = 1;
                break;
            }
        }
    }

    // SAFETY: `ctx` is null or live, and `BN_CTX_end` accepts a null context.
    unsafe { BN_CTX_end(ctx) };
    ret
}

/// `int BN_generate_prime_ex2(BIGNUM *ret, int bits, int safe, const BIGNUM *add,`
/// `const BIGNUM *rem, BN_GENCB *cb, BN_CTX *ctx)` —
/// `crypto/bn/bn_prime.c:123-208`.
///
/// Both refusals are here and neither draws: `bits < 2` is `BN_R_BITS_TOO_SMALL`,
/// and so is the safe-prime case below six bits that is not three (the authority's
/// comment names the two unreachable safe primes, 11 and 23).
///
/// The `checks` used for an ordinary candidate is `bn_mr_min_checks(bits)`, and for a
/// safe prime the pair `(p, (p-1)/2)` is tested once per round, which is why the safe
/// arm costs `2 * checks` Miller-Rabin rounds per accepted prime.
///
/// # Safety
///
/// `ret` must be null or a live, uniquely-owned `BIGNUM`; `add` and `rem` must each be
/// null or live; `cb` must be null or a live `BN_GENCB` whose callback is safe to
/// call; `ctx` must be null or a live `BN_CTX`.
#[no_mangle]
pub unsafe extern "C" fn BN_generate_prime_ex2(
    ret: *mut BigNum,
    bits: c_int,
    safe: c_int,
    add: *const BigNum,
    rem: *const BigNum,
    cb: *mut BnGencb,
    ctx: *mut BnCtx,
) -> c_int {
    guard_ffi(0, || {
        let checks = bn_mr_min_checks(bits);
        let mut found: c_int = 0;

        'body: {
            if bits < 2 {
                /* There are no prime numbers this small. */
                // SAFETY: the site is a compile-time constant.
                unsafe { raise_site(&BN_PRIME_135) };
                break 'body;
            } else if add.is_null() && safe != 0 && bits < 6 && bits != 3 {
                /*
                 * The smallest safe prime (7) is three bits.
                 * But the following two safe primes with less than 6 bits (11, 23)
                 * are unreachable for BN_rand with BN_RAND_TOP_TWO.
                 */
                // SAFETY: the site is a compile-time constant.
                unsafe { raise_site(&BN_PRIME_143) };
                break 'body;
            }

            // `OPENSSL_calloc(NUMPRIMES, sizeof(*mods))`. The zeroing is not
            // observable — every slot the sieve reads is one it has written — but it
            // is what the authority does.
            let mods = CRYPTO_calloc(
                NUMPRIMES,
                core::mem::size_of::<PrimeT>(),
                FILE.as_ptr(),
                LINE,
            )
            .cast::<PrimeT>();
            if mods.is_null() {
                break 'body;
            }

            // SAFETY: `ctx` is null or live per this function's `# Safety` section.
            unsafe { BN_CTX_start(ctx) };
            // SAFETY: as above.
            let t = unsafe { BN_CTX_get(ctx) };

            // `aborted` is `t == NULL` and every failed step below; the authority's
            // `goto err` reaches the same place, and `is_prime` is what tells the two
            // apart for `found`.
            let mut is_prime = false;
            if !t.is_null() {
                let mut c1: c_int = 0;
                'candidate: loop {
                    // SAFETY: `ret` is null or live, `mods` is writable for `NUMPRIMES`
                    // entries, `add`/`rem` are null or live and `ctx` is null or live,
                    // all per this function's `# Safety` section.
                    let ok = unsafe {
                        if add.is_null() {
                            probable_prime(ret, bits, safe, mods, ctx)
                        } else {
                            probable_prime_dh(ret, bits, safe, mods, add, rem, ctx)
                        }
                    };
                    if ok == 0 {
                        break 'candidate;
                    }

                    // SAFETY: `cb` is null or live.
                    if unsafe { BN_GENCB_call(cb, 0, c1) } == 0 {
                        /* aborted */
                        break 'candidate;
                    }
                    c1 += 1;

                    if safe == 0 {
                        // SAFETY: `ret` is null or live, `ctx` is live, `cb` is null or
                        // live.
                        let i = unsafe { bn_is_prime_int(ret, checks, ctx, 0, cb) };
                        if i == -1 {
                            break 'candidate;
                        }
                        if i == 0 {
                            continue 'candidate;
                        }
                    } else {
                        /*
                         * for "safe prime" generation, check that (p-1)/2 is prime.
                         * Since a prime is odd, We just need to divide by 2
                         */
                        // SAFETY: `t` and `ret` are pool temporaries and `ctx` is live.
                        if unsafe { BN_rshift1(t, ret) } == 0 {
                            break 'candidate;
                        }
                        let mut i: c_int = 0;
                        let mut rejected = false;
                        while i < checks {
                            // SAFETY: as above, with `cb` null or live.
                            let j = unsafe { bn_is_prime_int(ret, 1, ctx, 0, cb) };
                            if j == -1 {
                                break 'candidate;
                            }
                            if j == 0 {
                                rejected = true;
                                break;
                            }
                            // SAFETY: as above, with `t` the cofactor.
                            let j = unsafe { bn_is_prime_int(t, 1, ctx, 0, cb) };
                            if j == -1 {
                                break 'candidate;
                            }
                            if j == 0 {
                                rejected = true;
                                break;
                            }
                            // SAFETY: `cb` is null or live.
                            if unsafe { BN_GENCB_call(cb, 2, c1 - 1) } == 0 {
                                break 'candidate;
                            }
                            /* We have a safe prime test pass */
                            i += 1;
                        }
                        if rejected {
                            continue 'candidate;
                        }
                    }
                    /* we have a prime :-) */
                    is_prime = true;
                    break 'candidate;
                }
                if is_prime {
                    found = 1;
                }
            }

            // `OPENSSL_free(mods)`.
            // SAFETY: `mods` came from the `CRYPTO_calloc` above and has not been
            // released; `BN_CTX_end` matches the `BN_CTX_start` above.
            unsafe {
                CRYPTO_free(mods.cast(), FILE.as_ptr(), LINE);
                BN_CTX_end(ctx);
            }
        }
        found
    })
}

