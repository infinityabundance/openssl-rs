//! Phase 5 — the `tasn_typ.c` function family: the `d2i_*`/`i2d_*` wrappers for
//! the coded types, and `ASN1_NULL`'s allocator.
//!
//! The authority generates these with three macros, and every one of them is a
//! one-line forward to the shared machinery:
//!
//! ```text
//! IMPLEMENT_ASN1_ENCODE_FUNCTIONS_fname(stname, itname, fname)
//!     stname *d2i_##fname(stname **a, const unsigned char **in, long len)
//!     { return (stname *)ASN1_item_d2i((ASN1_VALUE **)a, in, len, ASN1_ITEM_rptr(itname)); }
//!     int i2d_##fname(const stname *a, unsigned char **out)
//!     { return ASN1_item_i2d((const ASN1_VALUE *)a, out, ASN1_ITEM_rptr(itname)); }
//! ```
//!
//! so there is no per-type behaviour here at all. That is the point: the type's
//! behaviour is its [`crate::asn1::items`] descriptor, and this module is the
//! naming layer that binds a symbol to one.
//!
//! Two families share the file because the authority groups them: the plain types
//! (`ASN1_OCTET_STRING` through `ASN1_BMPSTRING`, `ASN1_NULL`, `ASN1_OBJECT`) and
//! the multi-string types (`ASN1_PRINTABLE`, `DIRECTORYSTRING`, `DISPLAYTEXT`,
//! `ASN1_TIME`), which are declared `DECLARE_ASN1_FUNCTIONS_name(ASN1_STRING, X)`
//! and so take an `ASN1_STRING **` rather than an `X **`. The macro below carries
//! both spellings because the difference is visible in the installed headers.
//!
//! ## Why the null redirect is inside the shared decoder
//!
//! `d2i_*(NULL, pp, len)` is legal, and it is the *item* machinery that
//! accommodates it — `ASN1_item_d2i` redirects a null value slot to a local. The
//! wrappers therefore pass `a` through untouched, including when it is null, and
//! [`crate::asn1::d2i::item_d2i`] is where the redirect happens. Doing it here
//! instead would mean twenty places could get it wrong.
//!
//! ## `ASN1_NULL`
//!
//! `typedef int ASN1_NULL`, so `ASN1_NULL_new` answers an `int *` and its value is
//! the sentinel `1` — an address that is never dereferenced, because a NULL's
//! content is empty and `ASN1_NULL_free` is a no-op. That is not a shortcut
//! invented here: `asn1_primitive_new`'s `V_ASN1_NULL` arm stores
//! `(ASN1_VALUE *)1` and `ossl_asn1_primitive_free`'s is `break`.
//!
//! SPDX-License-Identifier: Apache-2.0

use core::ffi::{c_int, c_long, c_uchar};

use crate::asn1::d2i::item_d2i;
use crate::asn1::i2d::item_i2d;
use crate::asn1::items::*;
use crate::asn1::layout::Asn1String;
use crate::ffi::guard_ffi;

/// Declare one `d2i_*`/`i2d_*` pair over a named item.
///
/// The two identifiers are written out at each use because a macro cannot build a
/// `#[no_mangle]` symbol from another token — the constraint
/// [`crate::asn1::string`]'s `define_new_free` records. The macro exists so the
/// *shape* is stated once: a null-tolerant decode through the shared decoder, and
/// an encode whose three output conventions live in
/// [`crate::asn1::i2d::item_i2d`].
macro_rules! item_functions {
    ($getter:ident, $d2i:ident, $i2d:ident, $ty:literal, $origin:literal) => {
        #[doc = concat!(
                    "`", $ty, " *", stringify!($d2i), "(", $ty,
                    " **a, const unsigned char **pp, long len)`"
                )]
        ///
        #[doc = concat!(
                    "Generated by `tasn_typ.c`'s `IMPLEMENT_ASN1_ENCODE_FUNCTIONS_name(", $origin,
                    ", ", $origin, ")` over the item `", stringify!($getter), "`."
                )]
        ///
        /// # Safety
        ///
        /// `pp` must point to a slot holding a readable pointer to `len` bytes.
        /// `a` must be null or point to a slot holding null or a live value of this
        /// type.
        #[no_mangle]
        pub unsafe extern "C" fn $d2i(
            a: *mut *mut Asn1String,
            pp: *mut *const c_uchar,
            len: c_long,
        ) -> *mut Asn1String {
            guard_ffi(core::ptr::null_mut(), || {
                // SAFETY: the caller's contract; `$getter()` answers a static item.
                unsafe { item_d2i(a, pp, len, $getter()) }
            })
        }

        #[doc = concat!("`int ", stringify!($i2d), "(const ", $ty, " *a, unsigned char **out)`")]
        ///
        #[doc = concat!(
                    "The encode half of the pair above. `out == NULL` answers the length, ",
                    "`*out == NULL` allocates, and otherwise the caller's buffer is written ",
                    "and its pointer advanced."
                )]
        ///
        /// # Safety
        ///
        /// `a` must be null or a live value of this type. `out` must be null or
        /// point to a slot holding null or a pointer with room for the encoding.
        #[no_mangle]
        pub unsafe extern "C" fn $i2d(a: *const Asn1String, out: *mut *mut c_uchar) -> c_int {
            guard_ffi(0, || {
                // SAFETY: the caller's contract; `$getter()` answers a static item.
                unsafe { item_i2d(a, out, $getter()) }
            })
        }
    };
}

