// ---------------------------------------------------------------------------
// `ASN1_NULL` — the sentinel the authority stores and never dereferences
// ---------------------------------------------------------------------------

/// `ASN1_NULL *ASN1_NULL_new(void)`
///
/// Answers the sentinel `1`, not an allocation. `asn1_primitive_new`'s
/// `V_ASN1_NULL` arm stores `(ASN1_VALUE *)1` through the value slot, and
/// `ossl_asn1_primitive_free`'s is a bare `break`, so a caller that frees one and a
/// caller that never does are indistinguishable — which is the contract.
///
/// The clippy lint below wants `ptr::dangling_mut`, whose address comes from the
/// type's *alignment* — 4 for an `int`, not 1. The authority's sentinel is
/// literally `(ASN1_VALUE *)1`, and `ASN1_NULL_new()`'s result is a value a caller
/// can compare and print, so the lint's suggestion would change observable
/// behaviour.
#[allow(clippy::manual_dangling_ptr)]
#[no_mangle]
pub extern "C" fn ASN1_NULL_new() -> *mut c_int {
    1 as *mut c_int
}

/// `void ASN1_NULL_free(ASN1_NULL *a)`
///
/// A no-op, for the reason above: there is nothing behind the sentinel to release.
/// It is still an exported symbol because a caller must be able to call it, and
/// still takes its argument because the authority's signature does.
///
/// # Safety
///
/// The argument is never dereferenced, so any `ASN1_NULL *` is acceptable; the
/// contract is stated for the documented signature's sake.
#[no_mangle]
pub unsafe extern "C" fn ASN1_NULL_free(a: *mut c_int) {
    // The authority's `ossl_asn1_primitive_free` reaches a bare `break` for
    // `V_ASN1_NULL`, so nothing is released and nothing is read. The parameter is
    // named and dropped rather than omitted so the symbol's arity matches.
    let _ = a;
}

/// `ASN1_NULL *d2i_ASN1_NULL(ASN1_NULL **a, const unsigned char **pp, long len)`
///
/// `ASN1_NULL` is `int`, so the value slot is an `int **`; the decoder stores the
/// sentinel through it exactly as `ASN1_NULL_new` answers it.
///
/// # Safety
///
/// `pp` must point to a slot holding a readable pointer to `len` bytes. `a` must
/// be null or point to a slot holding null.
#[no_mangle]
pub unsafe extern "C" fn d2i_ASN1_NULL(
    a: *mut *mut c_int,
    pp: *mut *const c_uchar,
    len: c_long,
) -> *mut c_int {
    guard_ffi(core::ptr::null_mut(), || {
        // SAFETY: an `int **` and a value slot have the same representation, and
        // the caller's contract covers both readings.
        let ret = unsafe { item_d2i(a.cast::<*mut Asn1String>(), pp, len, ASN1_NULL_it()) };
        ret.cast::<c_int>()
    })
}

/// `int i2d_ASN1_NULL(const ASN1_NULL *a, unsigned char **out)`
///
/// A NULL's content is empty, so this writes one header of length zero. Note that
/// the value is never read: `asn1_ex_i2c`'s `V_ASN1_NULL` arm sets `cont = NULL,
/// len = 0` without dereferencing it. A **null** `a` is a different case — the
/// item's `utype` is not the `BOOLEAN` exception, so the shared encoder reports the
/// value absent and this answers 0 without writing anything.
///
/// # Safety
///
/// `a` must be null or an `ASN1_NULL *`. `out` must be null or point to a slot
/// holding null or a pointer with room for the encoding.
#[no_mangle]
pub unsafe extern "C" fn i2d_ASN1_NULL(a: *const c_int, out: *mut *mut c_uchar) -> c_int {
    guard_ffi(0, || {
        // SAFETY: as the decode above, read in the other direction.
        unsafe { item_i2d(a.cast::<Asn1String>(), out, ASN1_NULL_it()) }
    })
}
