/// `int ossl_DER_w_algorithmIdentifier_SLH_DSA(WPACKET *pkt, int tag, SLH_DSA_KEY *key)` —
/// `der_slh_dsa_key.c:24-47`.
///
/// # Safety
/// `pkt` live; `key` is the caller's live SLH-DSA key.
#[allow(non_snake_case)] // the authority's name is the contract
#[allow(non_upper_case_globals)] // the `NID_SLH_DSA_*` constants are the object table's own spelling
pub(crate) unsafe fn ossl_DER_w_algorithmIdentifier_SLH_DSA(
    pkt: *mut Wpacket,
    tag: c_int,
    key: *mut SlhDsaKey,
) -> c_int {
    // SAFETY: `key` is live per the contract; the two accessors take its own address.
    let nid = unsafe { ossl_slh_dsa_key_get_type(key) };
    let alg: &[u8] = match nid {
        NID_SLH_DSA_SHA2_128s => &OSSL_DER_OID_ID_SLH_DSA_SHA2_128S,
        NID_SLH_DSA_SHA2_128f => &OSSL_DER_OID_ID_SLH_DSA_SHA2_128F,
        NID_SLH_DSA_SHA2_192s => &OSSL_DER_OID_ID_SLH_DSA_SHA2_192S,
        NID_SLH_DSA_SHA2_192f => &OSSL_DER_OID_ID_SLH_DSA_SHA2_192F,
        NID_SLH_DSA_SHA2_256s => &OSSL_DER_OID_ID_SLH_DSA_SHA2_256S,
        NID_SLH_DSA_SHA2_256f => &OSSL_DER_OID_ID_SLH_DSA_SHA2_256F,
        NID_SLH_DSA_SHAKE_128s => &OSSL_DER_OID_ID_SLH_DSA_SHAKE_128S,
        NID_SLH_DSA_SHAKE_128f => &OSSL_DER_OID_ID_SLH_DSA_SHAKE_128F,
        NID_SLH_DSA_SHAKE_192s => &OSSL_DER_OID_ID_SLH_DSA_SHAKE_192S,
        NID_SLH_DSA_SHAKE_192f => &OSSL_DER_OID_ID_SLH_DSA_SHAKE_192F,
        NID_SLH_DSA_SHAKE_256s => &OSSL_DER_OID_ID_SLH_DSA_SHAKE_256S,
        NID_SLH_DSA_SHAKE_256f => &OSSL_DER_OID_ID_SLH_DSA_SHAKE_256F,
        _ => return 0,
    };
    // SAFETY: `pkt` is live per the contract, and `alg` is a `'static` array whose length is the
    // fourth argument.
    unsafe {
        (ossl_DER_w_begin_sequence(pkt, tag) != 0
            /* No parameters. */
            && ossl_DER_w_precompiled(pkt, -1, alg.as_ptr().cast::<c_uchar>(), alg.len()) != 0
            && ossl_DER_w_end_sequence(pkt, tag) != 0) as c_int
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The twelve OIDs are the authority's own generated bytes (`der_slh_dsa.h`'s `DER_OID_V_*`
    /// macros): `06 09`, the eight shifted arcs `60 86 48 01 65 03 04 03`, and a final arc running
    /// `0x14`..`0x1F` — FIPS 205's twelve `id-slh-dsa-*` OIDs, 2.16.840.1.101.3.4.3.20 through 31.
    #[test]
    fn the_oids_are_the_authoritys_generated_bytes() {
        let all: [[u8; 11]; 12] = [
            OSSL_DER_OID_ID_SLH_DSA_SHA2_128S,
            OSSL_DER_OID_ID_SLH_DSA_SHA2_128F,
            OSSL_DER_OID_ID_SLH_DSA_SHA2_192S,
            OSSL_DER_OID_ID_SLH_DSA_SHA2_192F,
            OSSL_DER_OID_ID_SLH_DSA_SHA2_256S,
            OSSL_DER_OID_ID_SLH_DSA_SHA2_256F,
            OSSL_DER_OID_ID_SLH_DSA_SHAKE_128S,
            OSSL_DER_OID_ID_SLH_DSA_SHAKE_128F,
            OSSL_DER_OID_ID_SLH_DSA_SHAKE_192S,
            OSSL_DER_OID_ID_SLH_DSA_SHAKE_192F,
            OSSL_DER_OID_ID_SLH_DSA_SHAKE_256S,
            OSSL_DER_OID_ID_SLH_DSA_SHAKE_256F,
        ];
        for (i, oid) in all.iter().enumerate() {
            assert_eq!(
                &oid[..10],
                &[0x06, 0x09, 0x60, 0x86, 0x48, 0x01, 0x65, 0x03, 0x04, 0x03],
                "oid {i}: header and shifted arcs"
            );
            assert_eq!(oid[10], 0x14 + i as u8, "oid {i}: final arc");
        }
    }
}
