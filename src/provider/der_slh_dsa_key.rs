//! Phase 8 — `providers/common/der/der_slh_dsa_key.c` and the `id-slh-dsa-*` OID table
//! `der_slh_dsa_gen.c` generates from `SLH_DSA.asn1`.
//!
//! This unit is `slh_dsa_sig.c.in`'s one prerequisite: `slh_dsa_set_alg_id_buffer` builds the
//! signature's AlgorithmIdentifier through `ossl_DER_w_algorithmIdentifier_SLH_DSA`
//! (`slh_dsa_sig.c.in:140`), selecting the OID by the key's own NID, and keeps it on the context
//! because it is part of the signature's *parameter* contract rather than of the operation — the
//! same shape as `der_ecx_key.c`, `der_dsa_sig.c` and `der_ec_sig.c`.
//!
//! ## The OIDs are precompiled literals, and they are transcribed rather than computed
//!
//! `providers/common/der/der_slh_dsa_gen.c` is generated by `oids_to_c.pm` from
//! `providers/common/der/SLH_DSA.asn1`, and every entry is the DER encoding of one OID with no
//! values to derive. `id-slh-dsa-sha2-128s` is `{ 2 16 840 1 101 3 4 3 20 }`, whose body is eight
//! *seven-bit-shifted* arcs (`60 86 48 01 65 03 04 03`) followed by the one final arc, and the
//! twelve differ only in that final arc: `0x14`..`0x1F`. The values below are read back from the
//! authority's own generated header (`der_slh_dsa.h`'s `DER_OID_V_*` macros), not typed from the
//! ASN.1 by hand.
//!
//! ## The writer switches on the key's NID, and the twelve arms are the twelve parameter sets
//!
//! `ossl_slh_dsa_key_get_type` (`slh_dsa_key.c:463-466`) answers `params->type`, the `NID_SLH_DSA_*`
//! that `slh_params.c`'s table carries. The `default:` arm answers 0, so a key whose type is not
//! one of the twelve yields no AlgorithmIdentifier — the refusal `slh_dsa_set_alg_id_buffer`
//! silently tolerates, because an absent identifier still leaves the operation valid.
//!
//! SPDX-License-Identifier: Apache-2.0

