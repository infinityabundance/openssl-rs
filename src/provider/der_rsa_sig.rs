//! Phase 8 — `providers/common/der/der_rsa_sig.c`: the RSA `WITH MD` AlgorithmIdentifier writer,
//! and the sixteen `*WithRSAEncryption` OIDs it selects from.
//!
//! This unit is one of `rsa_sig.c.in`'s three non-FIPS prerequisites: `rsa_generate_signature_aid`
//! calls `ossl_DER_w_algorithmIdentifier_MDWithRSAEncryption` for the PKCS#1 v1.5 pad mode, and the
//! identifier it writes is part of the signature's *parameter* contract rather than of the
//! operation — which is why the court can observe it through `OSSL_SIGNATURE_PARAM_ALGORITHM_ID`.
//!
//! ## The OIDs are precompiled literals, and they are transcribed rather than computed
//!
//! `providers/common/der/der_rsa_gen.c` is generated by `oids_to_c.pm` from
//! `providers/common/der/RSA.asn1`, and every entry is the DER encoding of one OID with no values
//! to derive. The values below are read back from the authority's own generated headers —
//! `der_rsa.h`'s `DER_OID_V_*` macros for the `pkcs-1` arcs and `der_digests.h`'s for the four
//! `sha3` ones, which `der_rsa_sig.c` reaches through its own `#define` aliases — not typed from
//! the ASN.1 by hand.
//!
//! ## What is here, and what is not
//!
//! `der_rsa_sig.c` defines exactly one function and it is transcribed whole. The other RSA
//! AlgorithmIdentifier writers (`ossl_DER_w_RSASSA_PSS_params` and the two
//! `ossl_DER_w_algorithmIdentifier_RSA*` functions) live in `providers/common/der/der_rsa_key.c`
//! and are a separate unit, transcribed as `src/provider/der_rsa_key.rs`.
//!
//! SPDX-License-Identifier: Apache-2.0

