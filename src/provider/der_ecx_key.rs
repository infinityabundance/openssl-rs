#[cfg(test)]
mod tests {
    use super::*;

    /// The four OIDs are the authority's own generated bytes: `der_ecx.h`'s `DER_OID_V_*` macros,
    /// which are `DER_P_OBJECT` (`0x06`), a length, and the arc body. Checked against the
    /// authority's values rather than against a second transcription (D392).
    #[test]
    fn the_ecx_oids_are_the_authoritys_generated_bytes() {
        assert_eq!(OSSL_DER_OID_ID_X25519, [0x06, 0x03, 0x2B, 0x65, 0x6E]);
        assert_eq!(OSSL_DER_OID_ID_X448, [0x06, 0x03, 0x2B, 0x65, 0x6F]);
        assert_eq!(OSSL_DER_OID_ID_ED25519, [0x06, 0x03, 0x2B, 0x65, 0x70]);
        assert_eq!(OSSL_DER_OID_ID_ED448, [0x06, 0x03, 0x2B, 0x65, 0x71]);
    }

    /// Each writer is a `SEQUENCE` around one OID: the four encodings are seven bytes each
    /// (`30 05` header, then the five-byte OID) and differ only in the final arc.
    #[test]
    fn each_writer_emits_its_oid_in_a_sequence() {
        let mut buf = [0u8; 32];
        for (writer, tail) in [
            (
                ossl_DER_w_algorithmIdentifier_X25519
                    as unsafe fn(*mut Wpacket, c_int, *mut EcxKey) -> c_int,
                0x6Eu8,
            ),
            (
                ossl_DER_w_algorithmIdentifier_X448
                    as unsafe fn(*mut Wpacket, c_int, *mut EcxKey) -> c_int,
                0x6F,
            ),
            (
                ossl_DER_w_algorithmIdentifier_ED25519
                    as unsafe fn(*mut Wpacket, c_int, *mut EcxKey) -> c_int,
                0x70,
            ),
            (
                ossl_DER_w_algorithmIdentifier_ED448
                    as unsafe fn(*mut Wpacket, c_int, *mut EcxKey) -> c_int,
                0x71,
            ),
        ] {
            let mut pkt = core::mem::MaybeUninit::<Wpacket>::uninit();
            // SAFETY: `pkt` is a live local, `buf` is this call's own, and the writer is one of the
            // four above. `WPACKET_init_der` fills the buffer from its end, so the bytes are read
            // back through `WPACKET_get_curr` once the top-level `SEQUENCE` has closed.
            unsafe {
                assert_eq!(
                    crate::packet::WPACKET_init_der(pkt.as_mut_ptr(), buf.as_mut_ptr(), 32),
                    1
                );
                assert_eq!(writer(pkt.as_mut_ptr(), -1, core::ptr::null_mut()), 1);
                assert_eq!(crate::packet::WPACKET_finish(pkt.as_mut_ptr()), 1);
                let mut written: usize = 0;
                crate::packet::WPACKET_get_total_written(pkt.as_mut_ptr(), &raw mut written);
                assert_eq!(written, 7);
                let start = crate::packet::WPACKET_get_curr(pkt.as_mut_ptr());
                assert_eq!(
                    core::slice::from_raw_parts(start, 7),
                    &[0x30, 0x05, 0x06, 0x03, 0x2B, 0x65, tail]
                );
                crate::packet::WPACKET_cleanup(pkt.as_mut_ptr());
            }
        }
    }
}
