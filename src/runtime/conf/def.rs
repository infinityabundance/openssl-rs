/// `scan_esc(conf, p)` — step over an escape sequence.
///
/// # Safety
/// `p` must point at the backslash of a NUL-terminated string.
unsafe fn scan_esc(conf: *const Conf, p: *mut c_char) -> *mut c_char {
    // SAFETY: `p` points inside the string; `p[1]` is the terminator at worst.
    if unsafe { is_eof(conf, *p.add(1)) } {
        // SAFETY: `p` is at the backslash and `p[1]` is the terminator, so
        // `p + 1` is the terminator itself, still inside the string.
        unsafe { p.add(1) }
    } else {
        // SAFETY: `p[1]` is not the terminator, so the escape has a second byte
        // and `p + 2` is at worst one past that byte, i.e. inside the string.
        unsafe { p.add(2) }
    }
}

/// `static char *eat_ws(CONF *conf, char *p)`
///
/// # Safety
/// `p` must point into a NUL-terminated string.
unsafe fn eat_ws(conf: *const Conf, p: *mut c_char) -> *mut c_char {
    let mut p = p;
    // SAFETY: the loop stops at the terminator, which `is_ws` rejects.
    while unsafe { is_ws(conf, *p) } && !unsafe { is_eof(conf, *p) } {
        // SAFETY: the body runs only for a whitespace byte that is not the
        // terminator, so the next byte is still inside the string.
        p = unsafe { p.add(1) };
    }
    p
}

/// `static void trim_ws(CONF *conf, char *start)`
///
/// Note the authority's `p--` before the backward scan: for a string that is
/// entirely whitespace, `p` starts one byte *before* `start`, and the `p >= start`
/// guard is what stops the scan. Reproduced because the write afterwards is what
/// terminates the value.
///
/// # Safety
/// `start` must point into a NUL-terminated string.
unsafe fn trim_ws(conf: *const Conf, start: *mut c_char) {
    let mut p = start;
    // SAFETY: the loop stops at the terminator.
    while !unsafe { is_eof(conf, *p) } {
        // SAFETY: the condition stopped at a non-terminator byte, so advancing
        // stays inside the string.
        p = unsafe { p.add(1) };
    }
    // SAFETY: `start` points into a NUL-terminated string and the scan above
    // stopped at its terminator, so `p - 1` is the last data byte (or, for an
    // empty string, one before `start`, which the guarded loop below never
    // dereferences).
    p = unsafe { p.sub(1) };
    // SAFETY: `p >= start` keeps the scan inside the string, and `is_ws` reads
    // only within it.
    while (p as usize) >= (start as usize) && unsafe { is_ws(conf, *p) } {
        // SAFETY: `is_ws` returned non-zero for `*p` and the `p >= start` guard
        // held, so this byte is inside the string.
        p = unsafe { p.sub(1) };
    }
    // SAFETY: the backward scan stops at or above `start`; if it ended below
    // (the empty case) the single `p + 1` restores it to `start`.
    p = unsafe { p.add(1) };
    // SAFETY: `p` is inside the string: the first `p++` was at most one past the
    // terminator, and the scan walks back at most to `start`.
    unsafe { *p = 0 };
}

/// `static char *eat_alpha_numeric(CONF *conf, char *p)`
///
/// # Safety
/// `p` must point into a NUL-terminated string.
unsafe fn eat_alpha_numeric(conf: *const Conf, p: *mut c_char) -> *mut c_char {
    let mut p = p;
    loop {
        // SAFETY: `p` stays inside the string; the terminator is neither an
        // escape nor alphanumeric, so the loop cannot run past it.
        unsafe {
            if is_esc(conf, *p) {
                p = scan_esc(conf, p);
                continue;
            }
            let dollar_ok = (*conf).flag_dollarid != 0 && is_dollar(conf, *p);
            if !(is_alnum_punct(conf, *p) || dollar_ok) {
                return p;
            }
            p = p.add(1);
        }
    }
}

/// `static char *scan_quote(CONF *conf, char *p)`
///
/// # Safety
/// `p` must point at the opening quote of a NUL-terminated string.
unsafe fn scan_quote(conf: *const Conf, p: *mut c_char) -> *mut c_char {
    // SAFETY: `p` points at the opening quote of a NUL-terminated string per the
    // caller's contract, so this byte is readable.
    let q = unsafe { *p };
    // SAFETY: the opening quote is not the terminator, so `p + 1` is inside the
    // string.
    let mut p = unsafe { p.add(1) };
    // SAFETY: the loop stops at the terminator.
    while !unsafe { is_eof(conf, *p) } && unsafe { *p } != q {
        // SAFETY: `p` is inside the string here.
        if unsafe { is_esc(conf, *p) } {
            // SAFETY: `p` is at a backslash whose escaped byte follows.
            p = unsafe { p.add(1) };
            // SAFETY: `p` is at the escaped byte, which is inside the string.
            if unsafe { is_eof(conf, *p) } {
                return p;
            }
        }
        // SAFETY: `*p` was not the terminator, so the next byte is in bounds.
        p = unsafe { p.add(1) };
    }
    // SAFETY: the loop stopped at the terminator or the closing quote; both are
    // inside the string.
    if unsafe { *p } == q {
        // SAFETY: `p` is at the closing quote, so `p + 1` is at worst the
        // terminator.
        p = unsafe { p.add(1) };
    }
    p
}

/// `static char *scan_dquote(CONF *conf, char *p)`
///
/// Unlike [`scan_quote`], a doubled quote is an escaped quote rather than the
/// end: `"a""b"` is `a"b` here and `ab` under the single-quote rule. Only the
/// `WIN32` table marks the double quote as its own class, so this is reachable
/// only through `NCONF_WIN32()`.
///
/// # Safety
/// `p` must point at the opening quote of a NUL-terminated string.
unsafe fn scan_dquote(conf: *const Conf, p: *mut c_char) -> *mut c_char {
    // SAFETY: `p` points at the opening quote of a NUL-terminated string per the
    // caller's contract, so this byte is readable.
    let q = unsafe { *p };
    // SAFETY: the opening quote is not the terminator, so `p + 1` is inside the
    // string.
    let mut p = unsafe { p.add(1) };
    // SAFETY: the loop stops at the terminator.
    while !unsafe { is_eof(conf, *p) } {
        // SAFETY: `p` is inside the string here.
        if unsafe { *p } == q {
            // SAFETY: `p` is at a quote, so the next byte is at worst the
            // terminator.
            if unsafe { *p.add(1) } == q {
                // SAFETY: the doubled quote is not the terminator, so `p + 1` is
                // the second quote and still inside the string.
                p = unsafe { p.add(1) };
            } else {
                break;
            }
        }
        // SAFETY: `*p` was not the terminator, so the next byte is in bounds.
        p = unsafe { p.add(1) };
    }
    // SAFETY: `p` is at the terminator or the closing quote, both inside the
    // string.
    if unsafe { *p } == q {
        // SAFETY: `p` is at the closing quote, so `p + 1` is at worst the
        // terminator.
        p = unsafe { p.add(1) };
    }
    p
}

/// `static void clear_comments(CONF *conf, char *p)`
///
/// Two phases, and the difference between them is the difference between `;` at
/// the start of a line and inside it: a "full-line comment" character is honoured
/// only before any non-whitespace, while `#` is honoured anywhere outside a
/// quoted region.
///
/// # Safety
/// `p` must point into a NUL-terminated string.
unsafe fn clear_comments(conf: *const Conf, p: *mut c_char) {
    let mut p = p;
    loop {
        // SAFETY: `p` is inside the string.
        if unsafe { is_fcomment(conf, *p) } {
            // SAFETY: `p` was inside the string when read above.
            unsafe { *p = 0 };
            return;
        }
        // SAFETY: `p` is inside the string; the loop returns at the terminator.
        if !unsafe { is_ws(conf, *p) } {
            break;
        }
        // SAFETY: `*p` is whitespace, not the terminator, so the next byte is in
        // bounds.
        p = unsafe { p.add(1) };
    }
    loop {
        // SAFETY: `p` stays inside the string: every branch either advances
        // within it or returns at the terminator.
        unsafe {
            if is_comment(conf, *p) {
                *p = 0;
                return;
            }
            if is_dquote(conf, *p) {
                p = scan_dquote(conf, p);
                continue;
            }
            if is_quote(conf, *p) {
                p = scan_quote(conf, p);
                continue;
            }
            if is_esc(conf, *p) {
                p = scan_esc(conf, p);
                continue;
            }
            if is_eof(conf, *p) {
                return;
            }
            p = p.add(1);
        }
    }
}

/// `CHECK_AND_SKIP_PREFIX(str, pre)` with `HAS_PREFIX`'s comparison.
///
/// Advances `s` past `pre` when it is a prefix. `pre` never contains a NUL, so
/// the scan stops at the first mismatch or at `s`'s own terminator.
///
/// # Safety
/// `s` must point into a NUL-terminated string.
unsafe fn check_and_skip_prefix(s: &mut *mut c_char, pre: &[u8]) -> bool {
    for (i, want) in pre.iter().enumerate() {
        // SAFETY: reading at most up to and including the terminator.
        if unsafe { *s.add(i) } as u8 != *want {
            return false;
        }
    }
    // SAFETY: every `pre` byte matched, so `pre.len()` bytes lie before `s`'s
    // terminator and the advanced pointer is at most the terminator.
    *s = unsafe { s.add(pre.len()) };
    true
}

/// `static int str_copy(CONF *conf, char *section, char **pto, char *from)`
///
/// Copies a value, unquoting and expanding variables. The subtle parts, all
/// reproduced:
///
/// * the destination starts at `strlen(from) + 1` and is grown *from that
///   length*, so the 65536 cap applies to the buffer length rather than to the
///   number of characters written;
/// * `from` itself is temporarily NUL-terminated to isolate the variable name and
///   then restored — twice, once before the NULL check and once after the copy;
/// * a quoted region is copied verbatim, with escapes stepped over but **not**
///   expanded, while `$` outside quotes is;
/// * `*pto` is freed before the new buffer is installed, so a caller may pass the
///   field it is replacing.
///
/// # Safety
/// `conf` live; `pto` writable and its current value NULL or a `CRYPTO_malloc`
/// buffer; `from` NUL-terminated and writable (it is modified in place).
unsafe fn str_copy(
    conf: *mut Conf,
    section: *mut c_char,
    pto: *mut *mut c_char,
    from: *mut c_char,
) -> c_int {
    let buf = BUF_MEM_new();
    if buf.is_null() {
        return 0;
    }
    // SAFETY: `from` is NUL-terminated per the caller's contract.
    let from_len = unsafe { sys::strlen(from) };
    // SAFETY: `buf` is live; a failed grow leaves it empty and reports 0.
    if unsafe { BUF_MEM_grow(buf, from_len + 1) } == 0 {
        // SAFETY: `buf` is a live, still-empty `BUF_MEM`.
        unsafe { BUF_MEM_free(buf) };
        return 0;
    }

    let mut from = from;
    let mut to = 0usize;

    // The `err:` label's only action is to release the working buffer; the
    // caller's `*pto` is left exactly as it was.
    macro_rules! bail {
        () => {{
            // No `unsafe` block here: every call site is already inside one.
            BUF_MEM_free(buf);
            return 0;
        }};
    }

    loop {
        // SAFETY: `from` stays inside the caller's string throughout; no branch
        // advances past its terminator without returning or breaking.
        unsafe {
            if is_quote(conf, *from) {
                let q = *from;
                from = from.add(1);
                while !is_eof(conf, *from) && *from != q {
                    if is_esc(conf, *from) {
                        from = from.add(1);
                        if is_eof(conf, *from) {
                            break;
                        }
                    }
                    (*buf).data.add(to).write(*from);
                    to += 1;
                    from = from.add(1);
                }
                if *from == q {
                    from = from.add(1);
                }
            } else if is_dquote(conf, *from) {
                let q = *from;
                from = from.add(1);
                while !is_eof(conf, *from) {
                    if *from == q {
                        if *from.add(1) == q {
                            from = from.add(1);
                        } else {
                            break;
                        }
                    }
                    (*buf).data.add(to).write(*from);
                    to += 1;
                    from = from.add(1);
                }
                if *from == q {
                    from = from.add(1);
                }
            } else if is_esc(conf, *from) {
                from = from.add(1);
                let mut v = *from;
                from = from.add(1);
                if is_eof(conf, v) {
                    break;
                } else if v == b'r' as c_char {
                    v = b'\r' as c_char;
                } else if v == b'n' as c_char {
                    v = b'\n' as c_char;
                } else if v == b'b' as c_char {
                    v = 0x08;
                } else if v == b't' as c_char {
                    v = b'\t' as c_char;
                }
                (*buf).data.add(to).write(v);
                to += 1;
            } else if is_eof(conf, *from) {
                break;
            } else if *from == b'$' as c_char
                && ((*conf).flag_dollarid == 0
                    || *from.add(1) == b'{' as c_char
                    || *from.add(1) == b'(' as c_char)
            {
                // try to expand it
                let mut rrp: *mut c_char = ptr::null_mut();
                let mut s = from.add(1);
                let mut q: c_char = 0;
                if *s == b'{' as c_char {
                    q = b'}' as c_char;
                } else if *s == b'(' as c_char {
                    q = b')' as c_char;
                }
                if q != 0 {
                    s = s.add(1);
                }
                let mut cp = section;
                let mut np = s;
                let mut e = np;
                while is_alnum(conf, *e) || ((*conf).flag_dollarid != 0 && is_dollar(conf, *e)) {
                    e = e.add(1);
                }
                // `rr`/`rrp` remember the first byte replaced by a terminator,
                // which for a `section::name` reference is the second colon.
                let mut rr: c_char = 0;
                if *e == b':' as c_char && *e.add(1) == b':' as c_char {
                    cp = np;
                    rrp = e;
                    rr = *e;
                    *rrp = 0;
                    e = e.add(2);
                    np = e;
                    while is_alnum(conf, *e) || ((*conf).flag_dollarid != 0 && is_dollar(conf, *e))
                    {
                        e = e.add(1);
                    }
                }
                let r = *e;
                *e = 0;
                let rp = e;
                if q != 0 {
                    if r != q {
                        raise_site(&CONF_DEF_737);
                        bail!();
                    }
                    e = e.add(1);
                }
                let p = _CONF_get_string(conf, cp, np);
                if !rrp.is_null() {
                    *rrp = rr;
                }
                *rp = r;
                if p.is_null() {
                    raise_site(&CONF_DEF_757);
                    bail!();
                }
                let newsize = sys::strlen(p) + (*buf).length - ((e as usize) - (from as usize));
                if newsize > MAX_CONF_VALUE_LENGTH {
                    raise_site(&CONF_DEF_762);
                    bail!();
                }
                if BUF_MEM_grow_clean(buf, newsize) == 0 {
                    raise_site(&CONF_DEF_766);
                    bail!();
                }
                let mut q2 = p;
                while *q2 != 0 {
                    (*buf).data.add(to).write(*q2);
                    to += 1;
                    q2 = q2.add(1);
                }
                from = e;
                *rp = r;
            } else {
                (*buf).data.add(to).write(*from);
                to += 1;
                from = from.add(1);
            }
        }
    }

    // SAFETY: `to` never exceeds the buffer's length, so this write is inside the
    // allocation; and the old `*pto` is released before the new value is
    // installed, which is what lets a caller pass the field it is replacing.
    unsafe {
        (*buf).data.add(to).write(0);
        CRYPTO_free((*pto).cast::<c_void>(), ptr::null(), 0);
        *pto = (*buf).data;
        // Only the `BufMem` header is released: `data` now belongs to `*pto`.
        CRYPTO_free(buf.cast::<c_void>(), ptr::null(), 0);
    }
    1
}

/// `static int parsebool(const char *pval, int *flag)`
///
/// Case-insensitive `on`/`true`/`off`/`false`; anything else is
/// `CONF_R_INVALID_PRAGMA`. The comparison is `OPENSSL_strcasecmp`, whose
/// ASCII-only folding means a high byte can never match.
///
/// # Safety
/// `pval` NUL-terminated; `flag` writable.
unsafe fn parsebool(pval: *const c_char, flag: *mut c_int) -> c_int {
    // SAFETY: `pval` is NUL-terminated per the caller's contract.
    let on = unsafe { OPENSSL_strcasecmp(pval, c"on".as_ptr()) } == 0
        || unsafe { OPENSSL_strcasecmp(pval, c"true".as_ptr()) } == 0;
    // SAFETY: as above.
    let off = unsafe { OPENSSL_strcasecmp(pval, c"off".as_ptr()) } == 0
        || unsafe { OPENSSL_strcasecmp(pval, c"false".as_ptr()) } == 0;
    if on {
        // SAFETY: `flag` is writable per the caller's contract.
        unsafe { *flag = 1 };
    } else if off {
        // SAFETY: as above.
        unsafe { *flag = 0 };
    } else {
        // SAFETY: the site is a compile-time constant, which is `raise_site`'s
        // only precondition.
        unsafe { raise_site(&CONF_DEF_201) };
        return 0;
    }
    1
}

