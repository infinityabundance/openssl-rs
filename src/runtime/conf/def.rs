/// A method table with a stable address.
///
/// `NCONF_default()` hands out a pointer to one of these and callers compare it
/// by identity, so it must be a `static` rather than a `const`. The wrapper
/// exists only to carry the `Sync` assertion; `repr(transparent)` keeps the
/// address and layout identical to the inner table.
#[repr(transparent)]
pub struct ConfMethodCell(pub ConfMethod);

// SAFETY: every field of the table is a function pointer or a pointer to a
// string literal, and nothing writes to it after initialisation. Its address is
// what `NCONF_default` publishes, which is why it must be a `static`.
unsafe impl Sync for ConfMethodCell {}

