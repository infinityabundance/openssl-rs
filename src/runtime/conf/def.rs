//! Phase 4 — CONF: `crypto/conf/conf_def.c`, the default configuration method.
//!
//! This is the largest single behavioural surface in the stratum, because
//! `openssl.cnf` is *input that people write*: its grammar is a contract, not an
//! implementation detail. Everything below is reachable from a configuration
//! file an administrator or an application may hand to `NCONF_load`, and every
//! branch here is drivable by a file.
//!
//! ## The grammar, as the authority defines it
//!
//! * Lines are read with `BIO_gets` into a `BUF_MEM` that accumulates. A line
//!   that fills the read buffer without a newline, or that ends in a lone `\`, is
//!   *continued*: the next read appends to the same logical line. The two cases
//!   are the same `again` flag because both mean "do not parse yet".
//! * A UTF-8 BOM is stripped, and only on the first read.
//! * `#` and `;` start comments — but only through the two character-class
//!   tables, and the default table does **not** mark `;` as a comment at all.
//!   `CONF_type_win32` does, which is the entire observable difference between
//!   `NCONF_default()` and `NCONF_WIN32()`.
//! * `[section]` starts a section. A key may be qualified as `section::key`, and
//!   an unqualified key belongs to the section the *last* bracket opened — which
//!   is why the parser carries a `section` string that `str_copy` owns and
//!   reallocates.
//! * `name = value`, with the `=` optional after `.pragma`/`.include`.
//! * Values are bare or quoted with `'`/`"`, with `\r \n \b \t` escapes, and with
//!   `$name`, `${name}`, `$(name)` and `$section::name` expansion capped by
//!   `MAX_CONF_VALUE_LENGTH`.
//! * `.pragma dollarid|abspath|includedir` and `.include` of a file *or a
//!   directory*. Unknown pragmas are ignored; a missing `=` is an error.
//!
//! ## What the court is for
//!
//! Almost every one of those rules has a plausible-but-wrong implementation, and
//! the authority's source contains the traps: the BOM strip only on the first
//! call, the `key > 127` rejection in `is_keytype`, the "second last char is not
//! `\\`" condition on continuation, the trailing-`\r\n`-only trim loop, the
//! `buf->length` rather than content length in the expansion cap, and the fact
//! that `;` is punctuation in the default table. `RT-CONF` drives each one
//! against the authority rather than assuming.

