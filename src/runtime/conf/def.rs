/// `static int is_keytype(const CONF *conf, char c, unsigned short type)`
///
/// Bytes at or above `0x80` are rejected outright rather than looked up, so a
/// UTF-8 continuation byte is never whitespace, punctuation or a comment — which
/// is what makes a non-ASCII key a parse error rather than a silently different
/// key.
///
/// # Safety
/// `conf` must be live and its `meth_data` must point at a 128-entry table.
unsafe fn is_keytype(conf: *const Conf, c: c_char, ty: u16) -> bool {
    // SAFETY: `conf` is live per the caller's contract.
    let keytypes = unsafe { (*conf).meth_data } as *const u16;
    let key = c as u8;
    if key > 127 {
        return false;
    }
    // SAFETY: `key <= 127`, so this is inside the table.
    (unsafe { *keytypes.add(key as usize) } & ty) != 0
}

